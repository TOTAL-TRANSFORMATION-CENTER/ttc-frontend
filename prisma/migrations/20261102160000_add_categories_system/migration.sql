-- 1. Parent Table: Defines the dynamic categories (e.g., CHURCH_ROLE, REGION)
CREATE TABLE IF NOT EXISTS public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  code VARCHAR NOT NULL,
  name VARCHAR NOT NULL,
  description TEXT NULL,        
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,

  CONSTRAINT categories_pkey PRIMARY KEY (id),
  CONSTRAINT unique_category_code UNIQUE (code)
);

-- 2. Child Table: Stores the actual dropdown options linked to a parent category
CREATE TABLE IF NOT EXISTS public.category_values (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  category_id BIGINT NOT NULL,
  code VARCHAR NOT NULL,
  label VARCHAR NOT NULL,
  is_active BOOLEAN DEFAULT true NOT NULL,
  sort_order INT DEFAULT 0 NOT NULL, 
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,

  CONSTRAINT category_values_pkey PRIMARY KEY (id),
  CONSTRAINT fk_value_parent_category FOREIGN KEY (category_id) REFERENCES public.categories (id) ON DELETE CASCADE,
  CONSTRAINT unique_category_value_code UNIQUE (category_id, code)
);

